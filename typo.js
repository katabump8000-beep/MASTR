// خريطة مطبّعة (لتجاهل الفرق بين ة/ه و أ/ا)
const NORM_MAP = (() => {
    const m = {};
    for (const [k, v] of Object.entries(TYPO_MAP)) m[normalizeText(k)] = v;
    return m;
})();

// أوامر تقبل معطيات بعدها (تحويل الى فلان 50 ...)
const PREFIX_COMMANDS = ["تحويل", "شراء", "بيع", "تفاصيله", "مشاركة", "اشارك"];

function getCorrectedCommand(text) {
    if (!text) return null;

    // إزالة النقطة والبادئات
    let cleaned = String(text).trim();
    
    if (cleaned.startsWith(".")) {
        cleaned = cleaned.slice(1).trim();
    }

    if (!cleaned) return null;

    // تنظيف النص
    const normalized = normalizeText(cleaned);

    // البحث المباشر في الخريطة
    if (NORM_MAP[normalized]) {
        return "." + NORM_MAP[normalized];
    }

    // البحث بالبادئة: فقط للأوامر التي تأخذ معطيات (حتى لا تتفعل الأوامر من الكلام العادي)
    for (const key of PREFIX_COMMANDS) {
        if (normalized.startsWith(key + " ") && NORM_MAP[key]) {
            const rest = cleaned.slice(cleaned.indexOf(" ") + 1).trim();
            return "." + NORM_MAP[key] + (rest ? " " + rest : "");
        }
    }

    return null;
}


/**
 * يحاول تصحيح الأمر إذا كان مشابهاً لأمر موجود
 * @returns {Boolean} true إذا تم التعامل مع الرسالة (تصحيح + تنفيذ)
 */
async function handleTypo(sock, jid, msg, text, db, cleanSender, isBotOwner) {
    try {
        if (!text) return false;

        // إذا الرسالة تبدأ بنقطة، لا نعالجها هنا (handleCommand سيتعامل معها)
        if (String(text).startsWith(".")) return false;

        // محاولة التصحيح
        const corrected = getCorrectedCommand(text);
        if (!corrected) return false;

        // إرسال الأمر المصحح إلى handleCommand
        try {
            const { handleCommand } = require("./commands");

            // نحافظ على المنشن/الرد الأصلي (مثل: تفاصيله @user)
            const ctx = msg?.message?.extendedTextMessage?.contextInfo;
            const fakeMsg = {
                ...msg,
                message: ctx
                    ? { extendedTextMessage: { text: corrected, contextInfo: ctx } }
                    : { conversation: corrected }
            };

            const handled = await handleCommand(sock, jid, fakeMsg, {
                db,
                sender: msg?.key?.participant || msg?.key?.remoteJid,
                cleanSender,
                isGroup: true,
                isBotOwner: Boolean(isBotOwner),
                botNumber: cleanSender,
                text: corrected
            });

            return handled !== false;

        } catch (err) {
            console.error("❌ typo exec error:", err?.message);
            return false;
        }

    } catch (error) {
        console.error("❌ خطأ في handleTypo:", error?.message || error);
        return false;
    }
}


async function sendNextQuestion(sock, jid, db, gameState) {
    if (!gameState.isActive || gameState.isPaused) return;

    if (gameState.currentIndex >= gameState.totalQuestions) {
        gameState.stopGame();
        await safeSend(sock, jid, {
            text: getSarahaEndMessage()
        });
        return;
    }

    const question = gameState.questions[gameState.currentIndex];
    const questionNumber = gameState.currentIndex + 1;

    // ✅ إرسال السؤال بالشكل المطلوب
    await safeSend(sock, jid, {
        text: getSarahaQuestion(question, questionNumber)
    });

    gameState.currentIndex++;
    gameState.messageCount = 0;
    gameState.lastActivity = Date.now();

    if (gameState.timers.question) {
        clearTimeout(gameState.timers.question);
        gameState.timers.question = null;
    }

    gameState.timers.question = setTimeout(async () => {
        if (!gameState.isActive || gameState.isPaused) return;
        await sendNextQuestion(sock, jid, db, gameState);
    }, 30000);
}


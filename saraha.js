async function handleSarahaCommand(
    sock,
    jid,
    msg,
    db,
    saveDb,
    cleanSender,
    isBotOwner
) {
    try {
        if (activeSaraha[jid]) {
            await safeSend(sock, jid, {
                text: "⚠️ هناك لعبة صراحة قائمة بالفعل في هذه المجموعة!"
            }, { quoted: msg });
            return true;
        }

        db.gamePermissions = Array.isArray(db.gamePermissions) ? db.gamePermissions : [];
        const hasPermission = Boolean(isBotOwner) || db.gamePermissions.includes(cleanSender);

        if (!hasPermission) {
            await safeSend(sock, jid, {
                text: "⚠️ ليس لديك صلاحية لاستخدام هذا الأمر. يرجى التواصل مع المطور لمنحك الصلاحية."
            }, { quoted: msg });
            return true;
        }

        if (!hasNickname(db, cleanSender)) {
            await safeSend(sock, jid, {
                text: "❌ يجب أن يكون لديك لقب مسجل عبر .سجل لتتمكن من بدء اللعبة."
            }, { quoted: msg });
            return true;
        }

        // عرض التحميل
        await showLoading(sock, jid, msg);

        // اختيار 8 أسئلة عشوائية
        const questions = getRandomQuestions(8);

        const gameState = {
            questions: questions,
            currentIndex: 0,
            isActive: true,
            isPaused: false,
            lastActivity: Date.now(),
            messageCount: 0,
            totalQuestions: questions.length,
            currentQuestionIndex: 0,
            timers: {
                inactivity: null,
                question: null
            },
            listener: null,
            stopGame: function() {
                this.isActive = false;
                if (this.timers.inactivity) {
                    clearTimeout(this.timers.inactivity);
                    this.timers.inactivity = null;
                }
                if (this.timers.question) {
                    clearTimeout(this.timers.question);
                    this.timers.question = null;
                }
                if (this.listener) {
                    try {
                        sock.ev.off("messages.upsert", this.listener);
                    } catch (_) {}
                    this.listener = null;
                }
                delete activeSaraha[jid];
            }
        };

        activeSaraha[jid] = gameState;

        // إرسال رسالة الشرح
        await safeSend(sock, jid, {
            text: getSarahaStartMessage()
        }, { quoted: msg });

        // انتظار 2 ثانية ثم إرسال السؤال الأول
        setTimeout(async () => {
            if (!gameState.isActive) return;
            await sendNextQuestion(sock, jid, db, gameState);
        }, 2000);

        // مستمع الرسائل
        const listener = async (mObj) => {
            try {
                if (!gameState.isActive || gameState.isPaused) return;
                if (!mObj || !Array.isArray(mObj.messages) || !mObj.messages.length) return;

                const incomingMsg = mObj.messages[0];
                if (!incomingMsg?.message) return;
                if (incomingMsg.key?.remoteJid !== jid) return;

                const txt = getMessageText(incomingMsg.message);
                if (!txt) return;
                if (txt.startsWith(".")) return;

                gameState.lastActivity = Date.now();
                gameState.messageCount++;

                if (gameState.messageCount >= 6) {
                    gameState.messageCount = 0;
                    if (gameState.timers.question) {
                        clearTimeout(gameState.timers.question);
                        gameState.timers.question = null;
                    }
                    await sendNextQuestion(sock, jid, db, gameState);
                }

            } catch (error) {
                console.error("❌ خطأ في مستمع الصراحة:", error?.message || error);
            }
        };

        sock.ev.on("messages.upsert", listener);
        gameState.listener = listener;

        // مؤقت عدم النشاط (3 دقائق)
        gameState.timers.inactivity = setInterval(async () => {
            if (!gameState.isActive) {
                clearInterval(gameState.timers.inactivity);
                return;
            }

            const timeSinceLastActivity = Date.now() - gameState.lastActivity;
            if (timeSinceLastActivity > 3 * 60 * 1000) {
                gameState.stopGame();
                await safeSend(sock, jid, {
                    text: getSarahaInactiveStop()
                });
            }
        }, 30000);

        return true;

    } catch (error) {
        console.error("❌ خطأ في handleSarahaCommand:", error?.message || error);
        return false;
    }
}

